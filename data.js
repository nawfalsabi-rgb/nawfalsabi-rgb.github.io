const ASSET_POOL = Object.keys(ASSET_DIMS);

function makeImages(offset, overlayAt) {
	return [0, 1, 2, 3, 4].map((i) => {
		const src = ASSET_POOL[(offset + i) % ASSET_POOL.length];
		const dims = ASSET_DIMS[src];
		const image = { src, imgWidth: dims.w, imgHeight: dims.h };
		if (i === overlayAt) image.overlay = true;
		return image;
	});
}

